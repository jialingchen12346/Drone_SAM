def parse_class_ids(text: str) -> List[int]:
    ids: List[int] = []
    for raw in text.split(","):
        raw = raw.strip()
        if not raw:
            continue
        cls_id = int(raw)
        if cls_id < 0 or cls_id >= NUM_CLASSES:
            raise ValueError(f"Class id {cls_id} is out of range [0, {NUM_CLASSES - 1}]")
        ids.append(cls_id)
    if not ids:
        raise ValueError("At least one class id is required")
    return sorted(set(ids))


def build_class_balanced_sampler(
    dataset: FMBSubsetWithId,
    target_class_ids: Sequence[int],
    boost: float,
    seed: int,
) -> Tuple[WeightedRandomSampler, dict]:
    """Weight labeled samples by target-class presence and target rarity.

    FMB labels are stored as 1..14, so raw ids are shifted to 0..13 here.
    The rarity term prevents common classes such as Pole from dominating all
    samples while still increasing images where they appear.
    """
    if boost < 0:
        raise ValueError("--class-balanced-boost must be non-negative")

    target = np.array(sorted(set(target_class_ids)), dtype=np.int64)
    present = np.zeros((len(dataset), NUM_CLASSES), dtype=np.bool_)
    for row, base_idx in enumerate(dataset.indices):
        lbl_path = dataset.base.samples[base_idx]["lbl"]
        lbl = np.array(Image.open(lbl_path), dtype=np.int64)
        valid = (lbl >= 1) & (lbl <= NUM_CLASSES)
        if not valid.any():
            continue
        cls_present = np.unique(lbl[valid] - 1)
        present[row, cls_present] = True

    image_freq = present.mean(axis=0)
    rarity = 1.0 - image_freq
    weights = np.ones(len(dataset), dtype=np.float64)
    for cls_id in target:
        weights += boost * rarity[cls_id] * present[:, cls_id].astype(np.float64)
    weights = np.maximum(weights, 1e-6)

    generator = torch.Generator()
    generator.manual_seed(seed)
    sampler = WeightedRandomSampler(
        weights=torch.as_tensor(weights, dtype=torch.double),
        num_samples=len(dataset),
        replacement=True,
        generator=generator,
    )
    summary = {
        "targets": [(int(i), CLASSES[int(i)]) for i in target],
        "image_freq": {CLASSES[int(i)]: float(image_freq[int(i)]) for i in target},
        "weight_min": float(weights.min()),
        "weight_mean": float(weights.mean()),
        "weight_max": float(weights.max()),
    }
    return sampler, summary


