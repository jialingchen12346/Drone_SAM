class SegMetric:
    def __init__(self, num_classes: int, ignore_index: int = 255):
        self.num_classes = num_classes
        self.ignore_index = ignore_index
        self.confusion = np.zeros((num_classes, num_classes), dtype=np.int64)

    def reset(self) -> None:
        self.confusion[:] = 0

    def update(self, pred: np.ndarray, gt: np.ndarray) -> None:
        mask = (gt != self.ignore_index) & (gt >= 0) & (gt < self.num_classes)
        pred = pred[mask]
        gt = gt[mask]
        valid = (pred >= 0) & (pred < self.num_classes)
        idx = gt * self.num_classes + pred
        np.add.at(self.confusion.ravel(), idx[valid], 1)

    def compute(self, absent_score: Optional[float] = None) -> dict:
        cm = self.confusion
        tp = np.diag(cm)
        gt_sum = cm.sum(axis=1)
        pred_sum = cm.sum(axis=0)
        union = gt_sum + pred_sum - tp

        iou = np.where(union > 0, tp / union, np.nan)
        acc = np.where(gt_sum > 0, tp / gt_sum, np.nan)

        if absent_score is None:
            miou = float(np.nanmean(iou) * 100)
            macc = float(np.nanmean(acc) * 100)
        else:
            iou = np.where(np.isnan(iou), absent_score, iou)
            acc = np.where(np.isnan(acc), absent_score, acc)
            miou = float(iou.mean() * 100)
            macc = float(acc.mean() * 100)

        aacc = float(tp.sum() / max(cm.sum(), 1) * 100)
        return {
            "mIoU": miou,
            "mAcc": macc,
            "aAcc": aacc,
            "iou_per_class": (iou * 100).tolist(),
        }


class FMBSubsetWithId(Dataset):
    def __init__(self, base_dataset: FMBDataset, indices: Sequence[int]):
        self.base = base_dataset
        self.indices = list(indices)

    def __len__(self) -> int:
        return len(self.indices)

    def __getitem__(self, idx: int):
        base_idx = self.indices[idx]
        rgb, thm, gt = self.base[base_idx]
        sample = self.base.samples[base_idx]
        sample_id = f"{Path(sample['rgb']).parent.name}/{Path(sample['rgb']).name}"
        return rgb, thm, gt, sample_id


class PointLabelStore:
    def __init__(self, index_path: str):
        index_file = Path(index_path)
        with index_file.open("r", encoding="utf-8") as f:
            payload = json.load(f)
        root = index_file.parent

        table: Dict[str, dict] = {}
        for item in payload.get("items", []):
            sample_id = item["id"]
            npz_path = root / item["npz"]
            if not npz_path.exists():
                continue
            npz = np.load(npz_path)
            table[sample_id] = {
                "x": np.array(npz["x"], dtype=np.int32),
                "y": np.array(npz["y"], dtype=np.int32),
                "cls": np.array(npz["cls"], dtype=np.int64),
                "w": int(np.array(npz["w"])[0]),
                "h": int(np.array(npz["h"])[0]),
            }

        self.table = table
        self.meta = payload.get("meta", {})

    def get(self, sample_id: str) -> Optional[dict]:
        return self.table.get(sample_id)

    def __len__(self) -> int:
        return len(self.table)


class ProxyMaskStore:
    def __init__(self, index_path: str):
        index_file = Path(index_path)
        with index_file.open("r", encoding="utf-8") as f:
            payload = json.load(f)
        root = index_file.parent

        table: Dict[str, dict] = {}
        for item in payload.get("items", []):
            sample_id = item["id"]
            npz_path = root / item["npz"]
            if not npz_path.exists():
                continue
            table[sample_id] = {"npz": npz_path}

        self.table = table
        self.meta = payload.get("meta", {})

    def get(self, sample_id: str) -> Optional[dict]:
        rec = self.table.get(sample_id)
        if rec is None:
            return None
        npz = np.load(rec["npz"])
        return {
            "target": np.array(npz["target"], dtype=np.int64),
            "w": int(np.array(npz["w"])[0]),
            "h": int(np.array(npz["h"])[0]),
        }

    def __len__(self) -> int:
        return len(self.table)


def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def cosine_lr_schedule(
    optimizer: torch.optim.Optimizer,
    step: int,
    total_steps: int,
    warmup_steps: int,
    base_lrs: Sequence[float],
    min_lr_ratio: float = 1e-3,
) -> None:
    if step < warmup_steps:
        factor = step / max(1, warmup_steps)
    else:
        progress = (step - warmup_steps) / max(1, total_steps - warmup_steps)
        factor = min_lr_ratio + 0.5 * (1 - min_lr_ratio) * (1 + np.cos(np.pi * progress))

    for pg, base_lr in zip(optimizer.param_groups, base_lrs):
        pg["lr"] = base_lr * factor


