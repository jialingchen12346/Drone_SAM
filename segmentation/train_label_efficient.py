def distributed_info() -> Tuple[bool, int, int, int]:
    world_size = int(os.environ.get("WORLD_SIZE", "1"))
    distributed = world_size > 1
    rank = int(os.environ.get("RANK", "0"))
    local_rank = int(os.environ.get("LOCAL_RANK", "0"))
    return distributed, world_size, rank, local_rank


def setup_distributed(args: argparse.Namespace) -> Tuple[bool, int, int, torch.device]:
    distributed, world_size, rank, local_rank = distributed_info()
    if not distributed:
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        return False, rank, local_rank, device

    if not torch.cuda.is_available():
        raise RuntimeError("DDP requested via WORLD_SIZE>1, but CUDA is not available")
    torch.cuda.set_device(local_rank)
    init_kwargs = dict(backend=args.ddp_backend, init_method="env://")
    if "device_id" in inspect.signature(dist.init_process_group).parameters:
        init_kwargs["device_id"] = torch.device("cuda", local_rank)
    dist.init_process_group(**init_kwargs)
    return True, rank, local_rank, torch.device("cuda", local_rank)


def cleanup_distributed() -> None:
    if dist.is_available() and dist.is_initialized():
        dist.destroy_process_group()


